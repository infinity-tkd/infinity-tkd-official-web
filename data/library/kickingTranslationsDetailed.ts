/**
 * Universal Localized Kicking Item Provider
 * Seamlessly merges base English definitions with comprehensive translations
 * for Khmer, Chinese, and Korean.
 */
export function getLocalizedKickingItem(
  item: LibraryItem,
  lang: 'en' | 'km' | 'zh' | 'ko'
): LibraryItem {
  if (lang === 'en') return item

  const detailed = kickingDetailedTranslations[lang]?.[item.id]
  const basic = item.translations?.[lang]

  if (!detailed && !basic) return item

  return {
    ...item,
    ...basic,
    ...detailed,
    corePrinciples: detailed?.corePrinciples || item.corePrinciples,
    skillPrerequisites: detailed?.skillPrerequisites || item.skillPrerequisites,
    trainingProcess: detailed?.trainingProcess || item.trainingProcess,
    drillingMethods: detailed?.drillingMethods || item.drillingMethods,
    commonMistakesAndCorrections:
      detailed?.commonMistakesAndCorrections || item.commonMistakesAndCorrections,
    performanceAndApplication:
      detailed?.performanceAndApplication || item.performanceAndApplication,
    recoveryAndConditioning:
      detailed?.recoveryAndConditioning || item.recoveryAndConditioning,
  }
}
